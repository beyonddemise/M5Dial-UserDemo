#!/usr/bin/env python3
"""png2rgb565 - convert a PNG into a C header of RGB565 pixels.

Regenerates the lcd-image-converter style headers shipped with the M5Dial demo
(preset "Color R5G6B5", uint16_t, top_to_bottom, one source row per line).

The emitted word is the RGB565 value with its two bytes swapped (the high byte
of the colour is stored in the low byte of the uint16_t).  That is the layout
the original headers use and what M5GFX's pushImage()/pushSprite() expect for
a "swap565" buffer, so the arrays are drop-in replacements.

Usage:
    png2rgb565.py <in.png> <out.h> --name <ident> [--bg 0x000000]

API:
    convert(png_path, bg=0x000000) -> (width, height, [uint16 words])
    parse_header(path)             -> [uint16 words]
    main(argv)                     -> exit status
"""
import argparse
import os
import re
import sys

from PIL import Image

_BANNER = """\
/*******************************************************************************
* Generated by sketch/tools/png2rgb565.py from {src}
* (regenerates the lcd-image-converter headers of the original M5Dial demo,
*  originally generated by lcd-image-converter rev.030b30d - author/licence of
*  the artwork unchanged, see the upstream M5Dial-UserDemo repository)
*
* name: {name}
* preset: Color R5G6B5, 16 bit uint16_t (bytes swapped), RLE: no
* main scan direction: top_to_bottom, line scan direction: forward
* size: {w} x {h}
*******************************************************************************/
"""


def _to_swapped_rgb565(r, g, b):
    """Pack 8-bit r,g,b into RGB565 and swap the two bytes (see module doc)."""
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((v & 0xFF) << 8) | (v >> 8)


def convert(png_path, bg=0x000000):
    """Convert a PNG file to swapped-RGB565 words, row-major, top to bottom.

    Returns (width, height, words).  ``bg`` is accepted for CLI/API stability
    but is currently unused: alpha is ignored (see the why-comment below).
    """
    img = Image.open(png_path).convert("RGBA")
    # why: the shipped headers were produced by lcd-image-converter, which drops
    # the alpha channel and keeps the raw RGB.  Compositing on a background
    # (tried: black) matches the opaque temp_demo images but breaks all 8 launcher
    # icons, whose semi-transparent edge pixels are stored un-premultiplied.
    # Ignoring alpha reproduces all 19 shipped headers bit-exactly.
    words = [_to_swapped_rgb565(r, g, b) for r, g, b, _a in img.getdata()]
    return img.width, img.height, words


def parse_header(path):
    """Return the uint16 values of the array initialiser in a generated header."""
    text = open(path, encoding="utf-8").read()
    body = text.split("= {", 1)[1].split("};", 1)[0]
    body = re.sub(r"//[^\n]*", "", body)  # drop the ASCII-art preview comments
    return [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{1,4}", body)]


_REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def regen_note(png_path, out_path, name):
    """Return the one-line ``// Regenerable`` note with repo-relative paths."""
    def rel(p):
        # why: paths outside the repo (or on another drive on Windows) have no
        # meaningful repo-relative form; record the absolute path so the note
        # still points at the original files instead of failing.
        absp = os.path.abspath(p)
        try:
            r = os.path.relpath(absp, _REPO_ROOT)
        except ValueError:
            return absp.replace(os.sep, "/")
        if r == os.pardir or r.startswith(os.pardir + os.sep):
            return absp.replace(os.sep, "/")
        return r.replace(os.sep, "/")
    return ("// Regenerable (from repo root): python3 sketch/tools/png2rgb565.py "
            "%s %s --name %s\n" % (rel(png_path), rel(out_path), name))


def write_header(out_path, name, src, w, h, words, png_path=None):
    """Write ``static const uint16_t image_data_<name>[w*h]`` to out_path."""
    rows = [
        "    " + ", ".join("0x%04x" % v for v in words[y * w:(y + 1) * w])
        for y in range(h)
    ]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        if png_path:
            f.write(regen_note(png_path, out_path, name))
        f.write(_BANNER.format(src=src, name=name, w=w, h=h))
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("static const uint16_t image_data_%s[%d] = {\n" % (name, w * h))
        f.write(",\n".join(rows))
        f.write("\n};\n")


def main(argv=None):
    """CLI entry point; returns the process exit status."""
    ap = argparse.ArgumentParser(description="PNG -> RGB565 C header")
    ap.add_argument("png")
    ap.add_argument("header")
    ap.add_argument("--name", required=True, help="C identifier suffix (image_data_<name>)")
    ap.add_argument("--bg", type=lambda s: int(s, 0), default=0x000000,
                    help="background colour (currently unused; alpha is ignored)")
    args = ap.parse_args(argv)
    if not re.fullmatch(r"[A-Za-z_]\w*", args.name):
        ap.error("--name must be a valid C identifier")
    w, h, words = convert(args.png, args.bg)
    write_header(args.header, args.name, os.path.basename(args.png), w, h, words,
                 png_path=args.png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
